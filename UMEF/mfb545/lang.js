/* =====================================================================
   SWISS UMEF · MFB 545 Fintech — the language switch.

   The course exists twice: French (index.html, journee1.html …) and
   English (index-en.html, journee1-en.html …). The French pages are the
   SOURCE; the English ones are generated by _build/build_en.py from the
   translation tables in _build/i18n/ — edit the French page, update the
   table, rebuild. Same course id, module ids, data-work fields and
   namespace in both: a student can switch language and keep everything.

   Loaded FIRST on every page:
     • MFB545_LANG   'fr' | 'en', from <html lang>
     • T(fr, en)     picks the string for this page — used by the runtime
                     files (journee.js, presence.js, exercises.js,
                     courseprogress.js) whose copy is hard-coded
     • window.COURSE_LANG  so /shared/config.js hands login.js,
                     progress.js and chat.js the page's language
     • a [data-lang-switch] link records the choice (mfb545_lang); ONLY
       the hub redirects to the remembered language, so a pasted deep
       link always opens as pasted.
   ===================================================================== */
(function(){
  var L=(document.documentElement.getAttribute('lang')||'fr').slice(0,2);
  if(L!=='en')L='fr';
  window.MFB545_LANG=L;
  window.COURSE_LANG=L;
  window.T=function(fr,en){return L==='en'&&en!=null?en:fr;};
  /* journee1.html ↔ journee1-en.html */
  window.MFB545_HREF=function(href){return L==='en'?href.replace(/\.html/,'-en.html'):href;};
  document.addEventListener('click',function(e){
    var a=e.target.closest&&e.target.closest('[data-lang-switch]');
    if(!a)return;
    try{localStorage.setItem('mfb545_lang',a.getAttribute('data-lang-switch'));}catch(err){}
  });
  if(/\/(index(-en)?\.html)?$/.test(location.pathname)){
    var want=null;try{want=localStorage.getItem('mfb545_lang');}catch(err){}
    if(want&&want!==L&&(want==='fr'||want==='en'))location.replace(want==='en'?'index-en.html':'index.html');
  }
})();
